ALTER TABLE contract_audit_log
    ADD CONSTRAINT contract_audit_log_action_check
        CHECK (action IN (
    'CREATED',
    'UPDATED',
    'STATUS_CHANGED',
    'ATTACHMENT_ADDED'
    ));

CREATE TABLE contract_attachments (
                                      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                      contract_id BIGINT NOT NULL,
                                      file_name VARCHAR(255) NOT NULL,
                                      file_size BIGINT NOT NULL,
                                      file_data BYTEA NOT NULL,
                                      uploaded_by VARCHAR(255) NOT NULL,
                                      uploaded_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

                                      CONSTRAINT fk_contract_attachments_contract
                                          FOREIGN KEY (contract_id)
                                              REFERENCES contracts(id)
                                              ON DELETE CASCADE,

                                      CONSTRAINT chk_contract_attachments_file_size
                                          CHECK (file_size > 0 AND file_size <= 10485760)
);

CREATE INDEX idx_contract_attachments_contract_id
    ON contract_attachments(contract_id);
